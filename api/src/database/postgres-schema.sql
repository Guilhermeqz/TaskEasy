CREATE TABLE IF NOT EXISTS public.usuarios (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  email TEXT NOT NULL,
  senha_hash TEXT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS usuarios_email_lower_unique ON public.usuarios (LOWER(email));

CREATE TABLE IF NOT EXISTS public.tarefas (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INTEGER NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  titulo TEXT NOT NULL CHECK(length(trim(titulo)) BETWEEN 1 AND 120),
  descricao TEXT NOT NULL DEFAULT '',
  concluida INTEGER NOT NULL DEFAULT 0 CHECK(concluida IN (0, 1)),
  horario TEXT,
  lembrete_em TEXT,
  repetir_diariamente INTEGER NOT NULL DEFAULT 0 CHECK(repetir_diariamente IN (0, 1))
);
CREATE INDEX IF NOT EXISTS idx_tarefas_usuario ON public.tarefas(usuario_id);

-- Os clientes usam a API Express. Estas tabelas nao concedem acesso pela Data API.
ALTER TABLE public.usuarios ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.tarefas ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.usuarios, public.tarefas FROM PUBLIC;
REVOKE ALL ON SEQUENCE public.usuarios_id_seq, public.tarefas_id_seq FROM PUBLIC;
DO $block$
DECLARE client_role TEXT;
BEGIN
  FOREACH client_role IN ARRAY ARRAY['anon', 'authenticated'] LOOP
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = client_role) THEN
      EXECUTE format('REVOKE ALL ON TABLE public.usuarios, public.tarefas FROM %I', client_role);
      EXECUTE format('REVOKE ALL ON SEQUENCE public.usuarios_id_seq, public.tarefas_id_seq FROM %I', client_role);
    END IF;
  END LOOP;
END
$block$;
